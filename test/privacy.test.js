import test from "node:test";
import assert from "node:assert/strict";
import { privacyIssues, auditEntries, audit } from "../scripts/privacy.mjs";
import { mkdtemp, mkdir, writeFile, rm, realpath } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
const bytes = (s) => Buffer.from(s);
test("archive bytes reject private data even under an innocent file name", () => {
  const snapshot = Buffer.from(
    JSON.stringify({
      schemaVersion: 1,
      deviceId: "fixture",
      tasks: [],
      habits: [],
    }),
  ).toString("base64");
  assert.throws(
    () => auditEntries([{ name: "package/innocent.json", base64: snapshot }]),
    /personal workspace/,
  );
  assert.throws(
    () => auditEntries([{ name: "package/node_modules/x.js", base64: "" }]),
    /internal path/,
  );
  assert.throws(
    () => auditEntries([{ name: "../outside.txt", base64: "" }]),
    /Unsafe/,
  );
  assert.throws(
    () =>
      auditEntries([
        { name: "package/a", base64: "" },
        { name: "package/a", base64: "" },
      ]),
    /duplicate/,
  );
});
test("worktree audit catches generated bytes that differ from a safe index", async () => {
  const dir = await mkdtemp(path.join(tmpdir(), "time-desk-privacy-test-"));
  try {
    await mkdir(path.join(dir, "src"));
    await writeFile(path.join(dir, "src/public.js"), "export const value=1;");
    execFileSync("git", ["init"], { cwd: dir, stdio: "ignore" });
    execFileSync("git", ["add", "src/public.js"], {
      cwd: dir,
      stdio: "ignore",
    });
    await writeFile(
      path.join(dir, "src/public.js"),
      ["", "Users", "fixture", "secret"].join("/"),
    );
    await audit(dir);
    await assert.rejects(
      audit(dir, { worktree: true }),
      /Privacy audit failed/,
    );
  } finally {
    const resolved = await realpath(dir);
    assert.equal(path.dirname(resolved), await realpath(tmpdir()));
    assert.ok(path.basename(resolved).startsWith("time-desk-privacy-test-"));
    await rm(resolved, { recursive: true, force: true });
  }
});
test("privacy gate rejects task databases, chat logs and credential files", () => {
  for (const file of [
    "life_desk_v1.json",
    "data/life_desk_spirit.json",
    "session.jsonl",
    "profile.sqlite",
    "secrets/.env",
    "backups/export.json",
    ".npmrc",
  ])
    assert.ok(privacyIssues(file, bytes("{}")).length, file);
});
test("privacy gate detects renamed personal snapshots", () => {
  assert.ok(
    privacyIssues(
      "innocent.json",
      bytes(
        JSON.stringify({
          schemaVersion: 1,
          deviceId: "test",
          tasks: [],
          habits: [],
        }),
      ),
    ).includes("serialized personal workspace"),
  );
});
test("privacy gate detects home paths and credentials without printing values", () => {
  const home = ["", "Users", "someone", "Documents", "private"].join("/");
  assert.ok(
    privacyIssues("source.js", bytes(home)).includes("local home path"),
  );
  const token = ["gh", "p_", "x".repeat(40)].join("");
  assert.ok(
    privacyIssues("config.json", bytes(token)).includes("GitHub credential"),
  );
});
test("public metadata and compatibility format labels remain shareable", () => {
  assert.deepEqual(
    privacyIssues(
      "package.json",
      bytes(
        JSON.stringify({
          name: "dsh-time-desk",
          repository: "https://github.com/yubudong/dsh-time-desk",
        }),
      ),
    ),
    [],
  );
  assert.deepEqual(
    privacyIssues("src/model.js", bytes('format: "dsh-life-desk"')),
    [],
  );
});
